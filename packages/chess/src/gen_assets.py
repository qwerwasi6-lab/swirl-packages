#!/usr/bin/env python3
"""Generate assets.c: chess piece masks (DejaVu Sans) + UI font glyphs (Inter, from the SwirlOS kit)."""
import sys
from PIL import Image, ImageDraw, ImageFont

DEJAVU = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
INTER = {
    "reg": sys.argv[1] + "/Inter-Regular.ttf",
    "semi": sys.argv[1] + "/Inter-SemiBold.ttf",
}
OUT = sys.argv[2]

PS = 64  # piece mask size
filled_cps = [0x265F, 0x265E, 0x265D, 0x265C, 0x265B, 0x265A]   # P N B R Q K (filled)
line_cps   = [0x2659, 0x2658, 0x2657, 0x2656, 0x2655, 0x2654]   # outline

def render(font, cp, ox=0, oy=0):
    im = Image.new("L", (PS * 2, PS * 2), 0)
    ImageDraw.Draw(im).text((PS // 2 + ox, PS // 2 + oy), chr(cp), font=font, fill=255, anchor="mm")
    return im

pf = ImageFont.truetype(DEJAVU, 56)
fills, lines = [], []
for fc, lc in zip(filled_cps, line_cps):
    a = render(pf, fc)
    bb = a.getbbox()
    w = bb[2] - bb[0]
    dx = (PS // 2 + (PS - w) // 2) - bb[0]       # centre the glyph horizontally in the tile
    dy = (PS // 2 + PS - 5) - bb[3]              # bottom edge 5px above the tile bottom
    fa = render(pf, fc, dx, dy).crop((PS // 2, PS // 2, PS // 2 + PS, PS // 2 + PS))
    la = render(pf, lc, dx, dy).crop((PS // 2, PS // 2, PS // 2 + PS, PS // 2 + PS))
    fills.append(fa)
    lines.append(la)

# preview sheet
sheet = Image.new("RGB", (PS * 6, PS * 2), (120, 150, 90))
for i in range(6):
    for row, col in ((0, (250, 246, 235)), (1, (40, 40, 44))):
        t = Image.new("RGB", (PS, PS), col)
        sheet.paste(t, (i * PS, row * PS), fills[i])
        sheet.paste(Image.new("RGB", (PS, PS), (30, 30, 30) if row == 0 else (150, 150, 155)), (i * PS, row * PS), lines[i])
sheet.save(OUT + ".preview.png")

def carray(name, data, per=24):
    s = ["const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), per):
        s.append(",".join(str(b) for b in data[i:i + per]) + ",")
    s.append("};")
    return "\n".join(s)

out = ["/* GENERATED by gen_assets.py - do not edit. */", '#include "assets.h"', ""]
fd = bytearray()
for im in fills:
    fd += im.tobytes()
ld = bytearray()
for im in lines:
    ld += im.tobytes()
out.append(carray("g_piece_fill", fd))
out.append(carray("g_piece_line", ld))

def make_font(tag, path, px):
    f = ImageFont.truetype(path, px)
    data = bytearray()
    glyphs = []
    for cp in range(32, 127):
        ch = chr(cp)
        im = Image.new("L", (px * 3, px * 3), 0)
        ox, oy = px, px * 2
        ImageDraw.Draw(im).text((ox, oy), ch, font=f, fill=255, anchor="ls")
        bb = im.getbbox()
        adv = int(round(f.getlength(ch) * 8))
        if bb is None:
            glyphs.append((0, 0, 0, 0, 0, adv))
            continue
        crop = im.crop(bb)
        off = len(data)
        data += crop.tobytes()
        glyphs.append((off, crop.width, crop.height, bb[0] - ox, bb[1] - oy, adv))
    asc = -min(g[4] for g in glyphs if g[2])
    desc = max(g[4] + g[2] for g in glyphs if g[2])
    out.append(carray("g_font_%s_data" % tag, data, 32))
    out.append("const Glyph g_font_%s_glyphs[95] = {" % tag)
    for g in glyphs:
        out.append("{%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    return asc, desc

metrics = {}
metrics["s"] = make_font("s", INTER["reg"], 13)
metrics["m"] = make_font("m", INTER["semi"], 16)
metrics["l"] = make_font("l", INTER["semi"], 24)
out.append("const FontInfo g_fonts[3] = {")
for tag in "sml":
    out.append('{g_font_%s_glyphs,g_font_%s_data,%d},' % (tag, tag, metrics[tag][0]))
out.append("};")
open(OUT, "w").write("\n".join(out) + "\n")
print("wrote", OUT, "pieces", len(fd) + len(ld), "bytes; metrics", metrics)
